/**
 * Attempts to load a precomputed offline uncompressed RGBA8 planetary surface pack
 * (`/offline-cosmos-packs/textures/<planetId>-rgba8.bin` or `.jpg`) bundled inside the ~300MB APK
 * and apply it directly to the planet's Three.js material.
 */
export async function tryLoadOfflinePlanetTexture(
  planetId: string,
  onTextureLoaded: (tex: THREE.Texture) => void
): Promise<boolean> {
  // 1. Check if a real NASA photographic texture (.jpg) is bundled in /offline-cosmos-packs/textures/
  try {
    const jpgUrl = `/offline-cosmos-packs/textures/${planetId}.jpg`;
    const head = await fetch(jpgUrl, { method: 'HEAD' });
    const ct = head.headers.get('content-type') || '';
    if (head.ok && ct.includes('image')) {
      const loader = new THREE.TextureLoader();
      loader.load(jpgUrl, (tex) => {
        tex.colorSpace = THREE.SRGBColorSpace;
        tex.wrapS = THREE.RepeatWrapping;
        tex.wrapT = THREE.ClampToEdgeWrapping;
        tex.needsUpdate = true;
        onTextureLoaded(tex);
      });
      return true;
    }
  } catch {
    // Continue to binary RGBA8 pack check
  }

  // 2. Check if an uncompressed RGBA8 surface pack (.pak) is present and has valid RGBA header
  const packMap: Record<string, string> = {
    sun: 'pack-01-sun-parker-coronagraph-8k.pak',
    mercury: 'pack-02-mercury-messenger-albedo-8k.pak',
    venus: 'pack-03-venus-magellan-radar-8k.pak',
    earth: 'pack-04-earth-blue-marble-bathymetry-8k.pak',
    mars: 'pack-06-mars-mola-elevation-olympus-8k.pak',
    jupiter: 'pack-07-jupiter-juno-perijove-storms-8k.pak',
    saturn: 'pack-09-saturn-cassini-rings-enceladus-8k.pak',
    uranus: 'pack-10-uranus-neptune-kuiper-pluto-8k.pak',
  };

  const packFile = packMap[planetId];
  if (!packFile) return false;

  try {
    const url = `/offline-cosmos-packs/${packFile}`;
    // Read the first 512 bytes header + 2048x1024x4 RGBA8 texture slice (8,388,608 bytes)
    const sliceEnd = 512 + 2048 * 1024 * 4 - 1;
    const res = await fetch(url, {
      headers: { Range: `bytes=0-${sliceEnd}` },
    });
    if (!res.ok) return false;
    const buf = await res.arrayBuffer();
    if (buf.byteLength < 512 + 2048 * 1024 * 4) return false;

    const headerText = new TextDecoder().decode(new Uint8Array(buf, 0, 512)).trim();
    if (!headerText.includes('RGBA8_2048X1024_SURFACE_ATLAS')) return false;

    const pixelBytes = new Uint8Array(buf, 512, 2048 * 1024 * 4);
    const dataTex = new THREE.DataTexture(pixelBytes, 2048, 1024, THREE.RGBAFormat);
    dataTex.colorSpace = THREE.SRGBColorSpace;
    dataTex.wrapS = THREE.RepeatWrapping;
    dataTex.wrapT = THREE.ClampToEdgeWrapping;
    dataTex.generateMipmaps = true;
    dataTex.minFilter = THREE.LinearMipmapLinearFilter;
    dataTex.magFilter = THREE.LinearFilter;
    dataTex.needsUpdate = true;
    onTextureLoaded(dataTex);
    return true;
  } catch {
    return false;
  }
}
