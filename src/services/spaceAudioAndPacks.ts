class PlanetaryAudioEngine {
  private ctx: AudioContext | null = null;
  private stopCurrentFn: (() => void) | null = null;
  private activePlanetId: string | null = null;
  private audioElement: HTMLAudioElement | null = null;

  public getActivePlanetId(): string | null {
    return this.activePlanetId;
  }

  public stop(): void {
    if (this.stopCurrentFn) {
      this.stopCurrentFn();
      this.stopCurrentFn = null;
    }
    if (this.audioElement) {
      this.audioElement.pause();
      this.audioElement.src = '';
      this.audioElement = null;
    }
    this.activePlanetId = null;
  }

  public async togglePlanetAudio(planetId: string): Promise<boolean> {
    if (this.activePlanetId === planetId) {
      this.stop();
      return false;
    }
    this.stop();

    const profile = PLANET_AUDIO_PROFILES[planetId] || PLANET_AUDIO_PROFILES.sun;
    this.activePlanetId = planetId;

    // 1. Try playing the real pre-rendered offline WAV file from the 300MB APK pack first
    try {
      const wavUrl = `/offline-cosmos-packs/audio/${profile.wavFileName}`;
      const headRes = await fetch(wavUrl, { method: 'HEAD' });
      const contentType = headRes.headers.get('content-type') || '';
      if (headRes.ok && (contentType.includes('audio') || contentType.includes('octet-stream'))) {
        const audio = new Audio(wavUrl);
        audio.loop = true;
        audio.volume = 0.8;
        await audio.play();
        this.audioElement = audio;
        this.stopCurrentFn = () => {
          audio.pause();
          audio.src = '';
        };
        return true;
      }
    } catch {
      // Fallback to real-time multi-harmonic WebAudio synthesis
    }

    // 2. Real-time WebAudio multi-harmonic magnetosphere & plasma synthesis
    const AudioCtx = window.AudioContext || (window as unknown as { webkitAudioContext: typeof AudioContext }).webkitAudioContext;
    if (!this.ctx) {
      this.ctx = new AudioCtx();
    }
    if (this.ctx.state === 'suspended') {
      await this.ctx.resume();
    }

    const ctx = this.ctx;
    const masterGain = ctx.createGain();
    masterGain.gain.setValueAtTime(0.01, ctx.currentTime);
    masterGain.gain.exponentialRampToValueAtTime(0.32, ctx.currentTime + 0.6);
    masterGain.connect(ctx.destination);

    const oscillators: OscillatorNode[] = [];
    const lfos: OscillatorNode[] = [];

    profile.harmonics.forEach((mult, idx) => {
      const osc = ctx.createOscillator();
      const oscGain = ctx.createGain();
      osc.type = idx % 2 === 0 ? 'sine' : 'triangle';
      osc.frequency.setValueAtTime(profile.baseFreq * mult, ctx.currentTime);

      // Slow frequency & amplitude modulation to replicate plasma whistler drift
      const lfo = ctx.createOscillator();
      const lfoGain = ctx.createGain();
      lfo.type = 'sine';
      lfo.frequency.setValueAtTime(profile.modRate * (1 + idx * 0.27), ctx.currentTime);
      lfoGain.gain.setValueAtTime(profile.baseFreq * mult * 0.035, ctx.currentTime);
      lfo.connect(lfoGain);
      lfoGain.connect(osc.frequency);

      oscGain.gain.setValueAtTime(0.28 / (idx + 1), ctx.currentTime);
      osc.connect(oscGain);
      oscGain.connect(masterGain);

      osc.start();
      lfo.start();
      oscillators.push(osc);
      lfos.push(lfo);
    });

    // Filtered pink/plasma noise buffer
    const bufferSize = ctx.sampleRate * 3;
    const noiseBuffer = ctx.createBuffer(1, bufferSize, ctx.sampleRate);
    const output = noiseBuffer.getChannelData(0);
    let b0 = 0, b1 = 0, b2 = 0;
    for (let i = 0; i < bufferSize; i++) {
      const white = Math.random() * 2 - 1;
      b0 = 0.997 * b0 + white * 0.029;
      b1 = 0.985 * b1 + white * 0.032;
      b2 = 0.950 * b2 + white * 0.048;
      output[i] = (b0 + b1 + b2) * 0.35;
    }
    const whiteNoise = ctx.createBufferSource();
    whiteNoise.buffer = noiseBuffer;
    whiteNoise.loop = true;

    const filter = ctx.createBiquadFilter();
    filter.type = 'bandpass';
    filter.frequency.setValueAtTime(profile.baseFreq * 2.2, ctx.currentTime);
    filter.Q.setValueAtTime(3.2, ctx.currentTime);

    const filterLfo = ctx.createOscillator();
    const filterLfoGain = ctx.createGain();
    filterLfo.frequency.setValueAtTime(profile.modRate * 0.5, ctx.currentTime);
    filterLfoGain.gain.setValueAtTime(profile.baseFreq * 1.1, ctx.currentTime);
    filterLfo.connect(filterLfoGain);
    filterLfoGain.connect(filter.frequency);

    const noiseGain = ctx.createGain();
    noiseGain.gain.setValueAtTime(profile.noiseLevel, ctx.currentTime);

    whiteNoise.connect(filter);
    filter.connect(noiseGain);
    noiseGain.connect(masterGain);

    whiteNoise.start();
    filterLfo.start();

    this.stopCurrentFn = () => {
      try {
        oscillators.forEach((o) => o.stop());
        lfos.forEach((l) => l.stop());
        whiteNoise.stop();
        filterLfo.stop();
        masterGain.disconnect();
      } catch {
        // Ignore already stopped nodes
      }
    };

    return true;
  }
}

